/** Busca una cifra por id; lanza si no existe (los ids se validan en check:contenido). */
export function getCifra(id: string): Cifra {
  const cifra = CIFRAS.find((c) => c.id === id)
  if (!cifra) throw new Error(`Cifra inexistente: ${id}`)
  return cifra
}

